"""
Rebuilds the Stud Construction badge as vectors from the client's artwork
(brand/logo-source.png, the 1080px logo from their Instagram).

The artwork is crisp black on white, so each part is traced with potrace on a
4x upsample and kept as its own path so the site can color and animate parts:
the house outline, the S T U D letters, the crossing studs, and the small
"EST 2009" / "CONSTRUCTION" lines.

Outputs (one geometry, in the artwork's pixel coordinates):
  brand/out/*.svg, *.png              files for print, social, and the client
  public/brand/*, public/*.png        assets the site serves (favicons, OG image)
  src/components/brand/logo-paths.ts  path data the inline logo uses

Run: uv run --with pillow --with numpy python brand/build_logo.py   (needs potrace, rsvg-convert)
"""

import json
import re
import subprocess
from collections import deque
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

from bake import bake

HERE = Path(__file__).parent
SITE = HERE.parent
OUT = HERE / "out"
WORK = HERE / ".work"
SOURCE = HERE / "logo-source.png"

INK = "#151515"
PAPER = "#F5F3EF"
SCALE = 4


def components(ink):
    """4-connected component labels of a boolean image."""
    lab = np.zeros(ink.shape, int)
    n = 0
    h, w = ink.shape
    for y, x in zip(*np.nonzero(ink)):
        if lab[y, x]:
            continue
        n += 1
        q = deque([(y, x)])
        lab[y, x] = n
        while q:
            cy, cx = q.popleft()
            for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                ny, nx = cy + dy, cx + dx
                if 0 <= ny < h and 0 <= nx < w and ink[ny, nx] and not lab[ny, nx]:
                    lab[ny, nx] = n
                    q.append((ny, nx))
    return lab, n


def trace(gray, mask, name):
    keep = np.array(Image.fromarray((mask * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(5))) > 0
    isolated = np.where(keep, gray, 255).astype(np.uint8)
    big = Image.fromarray(isolated).resize((isolated.shape[1] * SCALE, isolated.shape[0] * SCALE), Image.LANCZOS)
    big = big.filter(ImageFilter.GaussianBlur(SCALE * 0.6))
    bitmap = np.array(big) < 128
    pbm = WORK / f"{name}.pbm"
    Image.fromarray(((~bitmap) * 255).astype(np.uint8)).convert("1").save(pbm)
    svg = WORK / f"{name}.svg"
    subprocess.run(["potrace", str(pbm), "-s", "-o", str(svg), "-a", "0.9", "-O", "2", "-t", "40", "--flat"],
                   check=True)
    return _round(bake(svg.read_text(), SCALE, 0, 0))


def _round(d):
    return re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.1f}".rstrip("0").rstrip("."), d)


def classify(lab, n):
    """Sort components into outline, small text, crossing studs, and letters by shape."""
    groups = {"outline": [], "text": [], "studs": [], "letters": []}
    box = None
    for i in range(1, n + 1):
        ys, xs = np.nonzero(lab == i)
        if len(ys) < 8:
            continue
        x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
        w, h = x1 - x0 + 1, y1 - y0 + 1
        fill = len(ys) / (w * h)
        if w > 500 and h > 500:
            groups["outline"].append(i)
            box = (int(x0), int(y0), int(x1) + 1, int(y1) + 1)
        elif h < 40:
            groups["text"].append(i)
        elif fill < 0.2:
            groups["studs"].append(i)
        else:
            groups["letters"].append(i)
    return groups, box


def svg_doc(view, body):
    x0, y0, x1, y1 = view
    w, h = x1 - x0, y1 - y0
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x0} {y0} {w} {h}" width="{w}" height="{h}">{body}</svg>\n'


def badge(p, color):
    return f'<path fill="{color}" fill-rule="evenodd" d="{p["outline"]} {p["letters"]} {p["studs"]} {p["text"]}"/>'


def png(svg, dest, width):
    subprocess.run(["rsvg-convert", str(svg), "-o", str(dest), "-w", str(width)], check=True)


def main():
    WORK.mkdir(exist_ok=True)
    OUT.mkdir(exist_ok=True)
    gray = np.array(Image.open(SOURCE).convert("L"))
    lab, n = components(gray < 128)
    groups, box = classify(lab, n)
    print({k: len(v) for k, v in groups.items()}, box)
    paths = {name: trace(gray, np.isin(lab, ids), name) for name, ids in groups.items()}
    paths["box"] = list(box)
    ts = SITE / "src/components/brand/logo-paths.ts"
    ts.parent.mkdir(parents=True, exist_ok=True)
    ts.write_text(
        "/**\n * Vector geometry of the Stud Construction badge, in the artwork's pixel coordinates.\n"
        " * Generated by brand/build_logo.py from brand/logo-source.png; do not edit by hand.\n */\n"
        f"export const logoPaths = {json.dumps(paths, indent=2, sort_keys=True)} as const;\n"
    )

    x0, y0, x1, y1 = box
    view = (x0 - 4, y0 - 4, x1 + 4, y1 + 4)
    for suffix, color in (("", INK), ("-white", "#FFFFFF")):
        (OUT / f"badge{suffix}.svg").write_text(svg_doc(view, badge(paths, color)))
        png(OUT / f"badge{suffix}.svg", OUT / f"badge{suffix}.png", 2000)

    public = SITE / "public"
    (public / "brand").mkdir(parents=True, exist_ok=True)
    png(OUT / "badge.svg", public / "brand/logo.png", 800)
    (public / "brand/mark.svg").write_text((OUT / "badge.svg").read_text())

    # Icons: the white badge on a near-black square, so it reads on light and dark tab bars.
    size = (y1 - y0) * 1.18
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    ix, iy = cx - size / 2, cy - size / 2
    icon = WORK / "icon.svg"
    icon.write_text(svg_doc((ix, iy, ix + size, iy + size),
                            f'<rect x="{ix}" y="{iy}" width="{size}" height="{size}" rx="{size * 0.18}" fill="{INK}"/>'
                            + badge(paths, "#FFFFFF")))
    png(icon, public / "favicon.png", 64)
    png(icon, public / "apple-touch-icon.png", 180)
    png(icon, public / "icon-512.png", 512)

    og = WORK / "og.svg"
    s = 470 / (y1 - y0)
    og.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 630" width="1200" height="630">'
        f'<rect width="1200" height="630" fill="{INK}"/>'
        f'<g transform="translate(600 315) scale({s:.4f}) translate({-cx} {-cy})">{badge(paths, "#FFFFFF")}</g></svg>'
    )
    png(og, public / "og-default.png", 1200)


if __name__ == "__main__":
    main()
